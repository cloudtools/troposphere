from scripts.fix_copyright import revert_copyright_only_change

HEADER_2025 = "# Copyright (c) 2012-2025, Mark Peek <mark@peek.org>\n"
HEADER_2026 = "# Copyright (c) 2012-2026, Mark Peek <mark@peek.org>\n"
MARKER = "# *** Do not modify - this file is autogenerated ***\n"


def generated_file(header: str, body: str = "") -> str:
    return header + "# All rights reserved.\n" + MARKER + body


def test_reverts_copyright_only_change():
    baseline = generated_file(HEADER_2025)
    current = generated_file(HEADER_2026)

    assert revert_copyright_only_change(current, baseline) == baseline


def test_preserves_code_changes():
    baseline = generated_file(HEADER_2025, "\nclass Old:\n    pass\n")
    current = generated_file(HEADER_2026, "\nclass New:\n    pass\n")

    assert revert_copyright_only_change(current, baseline) is None


def test_ignores_non_generated_files():
    baseline = HEADER_2025 + "# All rights reserved.\n"
    current = HEADER_2026 + "# All rights reserved.\n"

    assert revert_copyright_only_change(current, baseline) is None
