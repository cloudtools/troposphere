#!/usr/bin/env python3

import re
import subprocess
from pathlib import Path
from typing import Optional

GENERATED_MARKER = "# *** Do not modify - this file is autogenerated ***"
COPYRIGHT_LINE = re.compile(
    r"^# Copyright \(c\) 2012-\d{4}, Mark Peek <mark@peek.org>\r?\n?",
    re.MULTILINE,
)


def revert_copyright_only_change(current: str, baseline: str) -> Optional[str]:
    """Restore the baseline copyright when it is the only changed line."""

    if GENERATED_MARKER not in current or GENERATED_MARKER not in baseline:
        return None

    current_match = COPYRIGHT_LINE.search(current)
    baseline_match = COPYRIGHT_LINE.search(baseline)
    if current_match is None or baseline_match is None:
        return None

    if current_match.group(0) == baseline_match.group(0):
        return None

    marker = "# Copyright (c) 2012-YYYY, Mark Peek <mark@peek.org>\n"
    normalized_current = (
        current[: current_match.start()] + marker + current[current_match.end() :]
    )
    normalized_baseline = (
        baseline[: baseline_match.start()] + marker + baseline[baseline_match.end() :]
    )
    if normalized_current != normalized_baseline:
        return None

    return (
        current[: current_match.start()]
        + baseline_match.group(0)
        + current[current_match.end() :]
    )


def _git_index_text(repo_root: Path, path: Path) -> Optional[str]:
    result = subprocess.run(
        ["git", "show", f":{path.as_posix()}"],
        cwd=repo_root,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        return None
    return result.stdout


def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--", "troposphere/*.py"],
        cwd=repo_root,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        return 0

    changed = []
    for filename in result.stdout.splitlines():
        path = repo_root / filename
        if not path.is_file():
            continue

        current = path.read_text(encoding="utf-8")
        baseline = _git_index_text(repo_root, Path(filename))
        if baseline is None:
            continue

        updated = revert_copyright_only_change(current, baseline)
        if updated is None:
            continue

        path.write_text(updated, encoding="utf-8")
        changed.append(filename)

    if changed:
        print(f"Reverted copyright-only changes in {len(changed)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
